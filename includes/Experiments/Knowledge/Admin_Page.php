<?php
/**
 * Settings → Guidelines admin page.
 *
 * @package WordPress\AI\Experiments\Knowledge
 *
 * @since 1.3.0
 */

declare( strict_types=1 );

namespace WordPress\AI\Experiments\Knowledge;

// Exit if accessed directly.
defined( 'ABSPATH' ) || exit;

/**
 * Bootstraps the Guidelines page in wp-admin under Settings.
 *
 * The page slug matches the one Gutenberg uses for the same screen, so the URL
 * stays `options-general.php?page=guidelines-wp-admin` no matter which plugin
 * provides the page. Only the plugin that owns the knowledge implementation
 * registers it (see Knowledge::register()), so the two can never collide.
 *
 * @since 1.3.0
 */
class Admin_Page {

	/**
	 * The admin page slug.
	 *
	 * @since 1.3.0
	 *
	 * @var string
	 */
	private const PAGE_SLUG = 'guidelines-wp-admin';

	/**
	 * The `admin_enqueue_scripts` hook suffix for this page.
	 *
	 * @since 1.3.0
	 *
	 * @var string
	 */
	private const HOOK_SUFFIX = 'settings_page_' . self::PAGE_SLUG;

	/**
	 * The render callback generated by wp-build for the `guidelines` page.
	 *
	 * @since 1.3.0
	 *
	 * @var string
	 */
	private const RENDER_CALLBACK = 'ai_guidelines_wp_admin_render_page';

	/**
	 * Initializes the admin page hooks.
	 *
	 * @since 1.3.0
	 *
	 * @return void
	 */
	public function init(): void {
		add_action( 'admin_menu', array( $this, 'register_submenu' ) );

		// Priority 5 runs before the generated page enqueues its assets at 10.
		add_action( 'admin_enqueue_scripts', array( $this, 'enqueue_block_registry_scripts' ), 5 );
		add_action( 'admin_enqueue_scripts', array( $this, 'preload_rest' ), 6 );
		add_action( self::PAGE_SLUG . '_init', array( $this, 'register_script_module_translations' ) );
	}

	/**
	 * Registers the Guidelines submenu item under Settings.
	 *
	 * @since 1.3.0
	 *
	 * @internal Used in the admin_menu action.
	 *
	 * @return void
	 */
	public function register_submenu(): void {
		if ( ! function_exists( self::RENDER_CALLBACK ) ) {
			// phpcs:ignore WordPress.Security.NonceVerification.Recommended -- Reading query param for admin page detection only, no data processing.
			if ( isset( $_GET['page'] ) && self::PAGE_SLUG === $_GET['page'] ) {
				_doing_it_wrong(
					__METHOD__,
					esc_html__( 'Guidelines page render function not found. Run npm run build:routes to generate build assets.', 'ai' ),
					'1.3.0'
				);
			}
			return;
		}

		add_submenu_page(
			'options-general.php',
			__( 'Guidelines', 'ai' ),
			__( 'Guidelines', 'ai' ),
			'manage_options',
			self::PAGE_SLUG,
			self::RENDER_CALLBACK // @phpstan-ignore argument.type
		);
	}

	/**
	 * Registers the `ai` text domain for the route script modules.
	 *
	 * Pages built by wp-build enqueue their JS as script modules. Localizing the
	 * strings in those modules requires `wp_set_script_module_translations()`
	 * rather than `wp_set_script_translations()`.
	 *
	 * @since 1.3.0
	 *
	 * @internal Used in the guidelines-wp-admin_init action.
	 *
	 * @return void
	 */
	public function register_script_module_translations(): void {
		wp_set_script_module_translations( 'ai/routes/guidelines/content', 'ai' );
	}

	/**
	 * Enqueues wp-block-library on the Guidelines admin page.
	 *
	 * The page bootstraps a Core-blocks-only block registry on the client so it
	 * can list block names and icons without loading the whole block editor.
	 * That needs `registerCoreBlocks()` to be available.
	 *
	 * @since 1.3.0
	 *
	 * @internal Used in the admin_enqueue_scripts action.
	 *
	 * @param string $hook_suffix The current admin page.
	 * @return void
	 */
	public function enqueue_block_registry_scripts( string $hook_suffix ): void {
		if ( ! $this->is_guidelines_page( $hook_suffix ) ) {
			return;
		}

		wp_enqueue_script( 'wp-block-library' );
	}

	/**
	 * Preloads the guideline scopes registry on the Guidelines admin page.
	 *
	 * The client then renders its sections without an extra round trip. This
	 * mirrors the preloading the generated page template performs for site
	 * settings.
	 *
	 * @since 1.3.0
	 *
	 * @internal Used in the admin_enqueue_scripts action.
	 *
	 * @param string $hook_suffix The current admin page.
	 * @return void
	 */
	public function preload_rest( string $hook_suffix ): void {
		if ( ! $this->is_guidelines_page( $hook_suffix ) ) {
			return;
		}

		$preload_paths = array(
			'/wp/v2/knowledge/guideline-scopes',
			array( '/wp/v2/knowledge/guideline-scopes', 'OPTIONS' ),
		);

		$preload_data = array();
		foreach ( $preload_paths as $preload_path ) {
			// The stub types $path as a string, but WordPress also accepts an
			// array( path, method ) pair, which is how the OPTIONS request below
			// is preloaded.
			// @phpstan-ignore argument.type
			$preload_data = rest_preload_api_request( $preload_data, $preload_path );
		}

		wp_add_inline_script(
			'wp-api-fetch',
			sprintf(
				'wp.apiFetch.use( wp.apiFetch.createPreloadingMiddleware( %s ) );',
				wp_json_encode( $preload_data )
			),
			'after'
		);
	}

	/**
	 * Whether the current admin screen is the Guidelines page.
	 *
	 * @since 1.3.0
	 *
	 * @param string $hook_suffix The current admin page.
	 * @return bool True when this is the Guidelines page and the user may see it.
	 */
	private function is_guidelines_page( string $hook_suffix ): bool {
		return self::HOOK_SUFFIX === $hook_suffix && current_user_can( 'manage_options' );
	}
}
