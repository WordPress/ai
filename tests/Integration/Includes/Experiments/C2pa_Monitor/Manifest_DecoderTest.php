	/**
	 * A store with no manifest superbox, or bytes that are not JUMBF at all,
	 * decode to null with a decode_jumbf error.
	 */
	public function test_unusable_store_returns_null_with_error(): void {
		$cases = array(
			'no manifests' => Fixtures::build_c2pa_store( array( Fixtures::jumbf_superbox( '63326173', 'not.a.manifest', array() ) ) ),
			'synthetic'    => Fixtures::build_c2pa_jumbf_store( Fixtures::synthetic_manifest_payload( 256 ) ),
			'garbage'      => 'not jumbf',
		);

		foreach ( $cases as $name => $bytes ) {
			list( $decoded, $errors ) = $this->decode( $bytes );

			$this->assertNull( $decoded, $name );
			$this->assertSame( array( 'decode_jumbf' ), array_column( $errors, 'stage' ), $name );
		}
	}

	/**
	 * The real signed XCA.jpg (v1 claim) decodes without errors.
	 */
	public function test_decodes_real_signed_jpeg(): void {
		$path = dirname( __DIR__, 4 ) . '/fixtures/c2pa/XCA.jpg';
		if ( ! is_file( $path ) ) {
			$this->markTestSkipped( 'XCA.jpg fixture not found.' );
		}

		$location = ( new Format_Detector() )->find_manifest_location( $path, 'jpeg' );
		$this->assertIsArray( $location );
		$manifest = ( new Manifest_Reader() )->read( $path, $location );
		$this->assertNotNull( $manifest );

		list( $decoded, $errors ) = $this->decode( $manifest->bytes );

		$this->assertSame( array(), $errors );
		$this->assertSame( 'contentauth:urn:uuid:ee7fc739-e619-44d3-a110-c9ff5dd2588d', $decoded['manifest_label'] );
		$this->assertSame(
			array(
				'name'    => 'make_test_images/0.22.0 c2pa-rs/0.22.0',
				'version' => null,
			),
			$decoded['claim_generator']
		);
		$this->assertSame( array( 'c2pa.opened', 'c2pa.color_adjustments' ), array_column( $decoded['actions'], 'action' ) );
		$this->assertNull( $decoded['digital_source_type'] );
	}
