/**
 * Verifies Manifest_Decoder builds the c2pa.decoded shape from v1 and v2
 * claims and routes every failure into the errors array.
 *
 * @since x.x.x
 */
class Manifest_DecoderTest extends WP_UnitTestCase {
	/**
	 * IPTC digital source type URI used in fixtures.
	 *
	 * @var string
	 */
	private const TRAINED_ALGORITHMIC_MEDIA = 'http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia';

	/**
	 * Decodes $bytes and returns the decoded value and errors.
	 *
	 * @param string $bytes Store bytes.
	 * @return array{0: array<string, mixed>|null, 1: list<array{stage: string, message: string}>}
	 */
	private function decode( string $bytes ): array {
		$errors  = array();
		$decoded = ( new Manifest_Decoder() )->decode( $bytes, $errors );
		return array( $decoded, $errors );
	}

	/**
	 * Builds a v2 claim generated by "Test Generator 2.1".
	 *
	 * @return string
	 */
	private function v2_claim(): string {
		return Fixtures::cbor(
			array(
				'instanceID'           => 'xmp:iid:1234',
				'claim_generator_info' => array(
					'name'    => 'Test Generator',
					'version' => '2.1',
				),
				'signature'            => 'self#jumbf=c2pa.signature',
			)
		);
	}

	/**
	 * A v2 claim with a v2 actions assertion decodes into the documented shape.
	 */
	public function test_decodes_v2_claim_and_actions(): void {
		// Tag 0 (date/time string) wraps `when`, as encoders emit it.
		$when    = (object) array( 'raw' => "\xC0" . Fixtures::cbor( '2026-10-13T10:00:00Z' ) );
		$actions = Fixtures::cbor(
			array(
				'actions' => array(
					array(
						'action'            => 'c2pa.created',
						'when'              => $when,
						'softwareAgent'     => array(
							'name'    => 'Image Model',
							'version' => '3',
						),
						'digitalSourceType' => self::TRAINED_ALGORITHMIC_MEDIA,
						'parameters'        => array( 'description' => 'dropped' ),
					),
					array( 'action' => 'c2pa.resized' ),
				),
			)
		);
		$store   = Fixtures::build_c2pa_store(
			array( Fixtures::c2pa_manifest( 'urn:c2pa:active', 'c2pa.claim.v2', $this->v2_claim(), array( 'c2pa.actions.v2' => $actions ) ) )
		);

		list( $decoded, $errors ) = $this->decode( $store );

		$this->assertSame( array(), $errors );
		$this->assertSame(
			array(
				'manifest_label'      => 'urn:c2pa:active',
				'claim_generator'     => array(
					'name'    => 'Test Generator',
					'version' => '2.1',
				),
				'digital_source_type' => self::TRAINED_ALGORITHMIC_MEDIA,
				'actions'             => array(
					array(
						'action'            => 'c2pa.created',
						'when'              => '2026-10-13T10:00:00Z',
						'softwareAgent'     => array(
							'name'    => 'Image Model',
							'version' => '3',
						),
						'digitalSourceType' => self::TRAINED_ALGORITHMIC_MEDIA,
					),
					array(
						'action'            => 'c2pa.resized',
						'when'              => null,
						'softwareAgent'     => null,
						'digitalSourceType' => null,
					),
				),
			),
			$decoded
		);
	}

	/**
	 * v1 claim_generator strings and softwareAgent strings normalize into the
	 * same { name, version } shape as v2.
	 */
	public function test_normalizes_v1_generator_strings(): void {
		$claim   = Fixtures::cbor( array( 'claim_generator' => 'make_test_images/0.33.1 c2pa-rs/0.33.1' ) );
		$actions = Fixtures::cbor(
			array(
				'actions' => array(
					array(
						'action'        => 'c2pa.opened',
						'softwareAgent' => 'Photo Editor 1.0',
					),
				),
			)
		);
		$store   = Fixtures::build_c2pa_store(
			array( Fixtures::c2pa_manifest( 'urn:uuid:v1', 'c2pa.claim', $claim, array( 'c2pa.actions' => $actions ) ) )
		);

		list( $decoded, $errors ) = $this->decode( $store );

		$this->assertSame( array(), $errors );
		$this->assertSame(
			array(
				'name'    => 'make_test_images/0.33.1 c2pa-rs/0.33.1',
				'version' => null,
			),
			$decoded['claim_generator']
		);
		$this->assertSame(
			array(
				'name'    => 'Photo Editor 1.0',
				'version' => null,
			),
			$decoded['actions'][0]['softwareAgent']
		);
		$this->assertNull( $decoded['digital_source_type'] );
	}

	/**
	 * A v1 claim's structured claim_generator_info list wins over the string.
	 */
	public function test_v1_claim_prefers_claim_generator_info(): void {
		$claim = Fixtures::cbor(
			array(
				'claim_generator'      => 'legacy/1.0',
				'claim_generator_info' => array(
					array(
						'name'    => 'Structured',
						'version' => '4.5',
					),
				),
			)
		);
		$store = Fixtures::build_c2pa_store( array( Fixtures::c2pa_manifest( 'urn:uuid:v1', 'c2pa.claim', $claim ) ) );

		list( $decoded ) = $this->decode( $store );

		$this->assertSame(
			array(
				'name'    => 'Structured',
				'version' => '4.5',
			),
			$decoded['claim_generator']
		);
	}

	/**
	 * The last manifest in the store is the active one.
	 */
	public function test_reads_last_manifest_as_active(): void {
		$parent = Fixtures::c2pa_manifest( 'urn:c2pa:parent', 'c2pa.claim', Fixtures::cbor( array( 'claim_generator' => 'parent/1' ) ) );
		$active = Fixtures::c2pa_manifest( 'urn:c2pa:active', 'c2pa.claim.v2', $this->v2_claim() );

		list( $decoded ) = $this->decode( Fixtures::build_c2pa_store( array( $parent, $active ) ) );

		$this->assertSame( 'urn:c2pa:active', $decoded['manifest_label'] );
		$this->assertSame( 'Test Generator', $decoded['claim_generator']['name'] );
	}

	/**
	 * An update manifest (c2um) can be the active manifest.
	 */
	public function test_update_manifest_can_be_active(): void {
		$standard = Fixtures::c2pa_manifest( 'urn:c2pa:standard', 'c2pa.claim', Fixtures::cbor( array( 'claim_generator' => 'standard/1' ) ) );
		$update   = Fixtures::jumbf_superbox(
			'6332756d',
			'urn:c2pa:update',
			array( Fixtures::jumbf_superbox( '6332636c', 'c2pa.claim.v2', array( Fixtures::jumbf_box( 'cbor', $this->v2_claim() ) ) ) )
		);

		list( $decoded, $errors ) = $this->decode( Fixtures::build_c2pa_store( array( $standard, $update ) ) );

		$this->assertSame( array(), $errors );
		$this->assertSame( 'urn:c2pa:update', $decoded['manifest_label'] );
		$this->assertSame( 'Test Generator', $decoded['claim_generator']['name'] );
	}

	/**
	 * A claim that decodes to something other than a map is reported.
	 */
	public function test_claim_that_is_not_a_map_is_reported(): void {
		$store = Fixtures::build_c2pa_store( array( Fixtures::c2pa_manifest( 'urn:c2pa:active', 'c2pa.claim.v2', Fixtures::cbor( 'not a map' ) ) ) );

		list( $decoded, $errors ) = $this->decode( $store );

		$this->assertNull( $decoded['claim_generator'] );
		$this->assertSame( array( 'decode_claim' ), array_column( $errors, 'stage' ) );
	}

	/**
	 * A claim superbox without a cbor content box is reported.
	 */
	public function test_claim_without_cbor_box_is_reported(): void {
		$manifest = Fixtures::jumbf_superbox(
			'63326d61',
