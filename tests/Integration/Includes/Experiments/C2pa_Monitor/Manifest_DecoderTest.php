	public function test_missing_claim_is_reported(): void {
		$manifest = Fixtures::jumbf_superbox( '63326d61', 'urn:c2pa:active', array() );

		list( $decoded, $errors ) = $this->decode( Fixtures::build_c2pa_store( array( $manifest ) ) );

