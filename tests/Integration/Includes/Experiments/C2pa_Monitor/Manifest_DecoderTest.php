	/**
	 * Actions are collected across multi-instance assertions, and the
	 * c2pa.created digital source type wins over earlier ones.
	 */
	public function test_collects_actions_across_assertion_instances(): void {
		$first  = Fixtures::cbor(
			array(
				'actions' => array(
					array(
						'action'            => 'c2pa.placed',
						'digitalSourceType' => 'http://cv.iptc.org/newscodes/digitalsourcetype/digitalCapture',
					),
				),
			)
		);
		$second = Fixtures::cbor(
			array(
				'actions' => array(
					array(
						'action'            => 'c2pa.created',
						'digitalSourceType' => self::TRAINED_ALGORITHMIC_MEDIA,
					),
				),
			)
		);
		$store  = Fixtures::build_c2pa_store(
			array(
				Fixtures::c2pa_manifest(
					'urn:c2pa:active',
					'c2pa.claim.v2',
					$this->v2_claim(),
					array(
						'c2pa.actions.v2'    => $first,
						'c2pa.hash.data'     => Fixtures::cbor( array( 'name' => 'jumbf manifest' ) ),
						'c2pa.actions.v2__1' => $second,
					)
				),
			)
		);

		list( $decoded ) = $this->decode( $store );

		$this->assertSame( array( 'c2pa.placed', 'c2pa.created' ), array_column( $decoded['actions'], 'action' ) );
		$this->assertSame( self::TRAINED_ALGORITHMIC_MEDIA, $decoded['digital_source_type'] );
	}

	/**
	 * Byte strings, non-strings, entries without an action and unknown keys
	 * never reach the record.
	 */
	public function test_drops_invalid_values(): void {
		$binary  = (object) array( 'raw' => Fixtures::cbor_head( 2, 2 ) . "\xFF\xFE" );
		$actions = Fixtures::cbor(
			array(
				'actions' => array(
					array(
						'action'            => 'c2pa.edited',
						'when'              => 12345,
						'softwareAgent'     => $binary,
						'digitalSourceType' => array( 'not', 'a', 'string' ),
						'unknown'           => 'dropped',
					),
					array( 'when' => '2026-01-01T00:00:00Z' ),
					'not a map',
					array( 'action' => $binary ),
				),
			)
		);
		$store   = Fixtures::build_c2pa_store(
			array( Fixtures::c2pa_manifest( 'urn:c2pa:active', 'c2pa.claim.v2', $this->v2_claim(), array( 'c2pa.actions.v2' => $actions ) ) )
		);

		list( $decoded, $errors ) = $this->decode( $store );

		$this->assertSame( array(), $errors );
		$this->assertSame(
			array(
				array(
					'action'            => 'c2pa.edited',
					'when'              => null,
					'softwareAgent'     => null,
					'digitalSourceType' => null,
				),
			),
			$decoded['actions']
		);
		$this->assertNotFalse( wp_json_encode( $decoded ) );
	}

	/**
	 * Long strings are truncated and the action list is capped.
	 */
	public function test_bounds_strings_and_action_count(): void {
		$entries = array_fill( 0, 150, array( 'action' => 'c2pa.edited' ) );
		$store   = Fixtures::build_c2pa_store(
			array(
				Fixtures::c2pa_manifest(
					'urn:c2pa:active',
					'c2pa.claim',
					Fixtures::cbor( array( 'claim_generator' => str_repeat( "\u{00e9}", 1000 ) ) ),
					array( 'c2pa.actions' => Fixtures::cbor( array( 'actions' => $entries ) ) )
				),
			)
		);

		list( $decoded ) = $this->decode( $store );

		$this->assertSame( 256, mb_strlen( $decoded['claim_generator']['name'] ) );
		$this->assertCount( 100, $decoded['actions'] );
	}

	/**
	 * A claim that fails to decode is reported, while actions still decode.
	 */
	public function test_malformed_claim_keeps_partial_result(): void {
		$actions = Fixtures::cbor( array( 'actions' => array( array( 'action' => 'c2pa.created' ) ) ) );
		$store   = Fixtures::build_c2pa_store(
			array( Fixtures::c2pa_manifest( 'urn:c2pa:active', 'c2pa.claim.v2', "\xBF\x61", array( 'c2pa.actions.v2' => $actions ) ) )
		);

		list( $decoded, $errors ) = $this->decode( $store );

		$this->assertIsArray( $decoded );
		$this->assertNull( $decoded['claim_generator'] );
		$this->assertSame( array( 'c2pa.created' ), array_column( $decoded['actions'], 'action' ) );
		$this->assertCount( 1, $errors );
		$this->assertSame( 'decode_claim', $errors[0]['stage'] );
		$this->assertStringStartsWith( 'c2pa.claim.v2: ', $errors[0]['message'] );
	}

